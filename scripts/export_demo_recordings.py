#!/usr/bin/env python3
"""Independently check replay objectives, then export the static demo assets."""
from pathlib import Path
import json,hashlib,shutil
import numpy as np
from sudoku_model import inspect,model
ROOT=Path(__file__).resolve().parents[1]
recordings={}
paths={'classic':ROOT/'results/demo/classic/fpga_seed1.json','paper':ROOT/'results/demo/paper/fpga_seed2.json','paper_initial':ROOT/'results/demo/paper/fpga_seed1.json','g15':ROOT/'results/demo/g15/sweep/fpga_seed10.json'}
if not paths['paper'].is_file():paths['paper']=ROOT/'results/demo/paper/rtl_seed1.json'
for key,path in paths.items():
    if not path.is_file():continue
    r=json.loads(path.read_text());prev=-1;best=None
    if key=='g15':
        q=np.load(ROOT/'python_code/G15.npy',allow_pickle=False);edges=np.argwhere(np.triu(q,1)).tolist()
        assert r['edges']==edges
    else:m=model(r['problem']['puzzle'])
    for f in r['frames']:
        assert f['cycle']>=prev;prev=f['cycle'];assert len(f['bits'])==(800 if key=='g15' else 729) and set(f['bits'])<={'0','1'}
        if key=='g15':
            cut=sum(f['bits'][a]!=f['bits'][b] for a,b in edges)
            assert cut==f['cut'] and (best is None or cut>=best);best=cut
        else:
            bits=np.array(list(f['bits']),dtype=np.int32);c=inspect(bits,r['problem']['puzzle'])
            assert c['clues_preserved'] and all(c[n]==f[n] for n in c)
            assert np.array_equal(bits[m['fixed'][:729]],m['initial'][:729][m['fixed'][:729]])
            assert best is None or c['energy']<=best;best=c['energy']
    r['recording_file']=str(path.relative_to(ROOT));r['recording_sha256']=hashlib.sha256(path.read_bytes()).hexdigest()
    r['problem']={k:v for k,v in r['problem'].items() if k not in ['initial_states','initial_fields','initial_bits','clamped']}
    recordings[key]=r
    print(key,r['mode'],len(r['frames']),'frames',best)
(ROOT/'demo/recordings.js').write_text('/* Generated by scripts/export_demo_recordings.py; actual independently checked runs. */\nwindow.QUBO_RECORDINGS='+json.dumps(recordings,separators=(',',':'))+';\n')
dest=ROOT/'ISCAS2025-FPGA-QUBO/demo';dest.mkdir(exist_ok=True)
for p in (ROOT/'demo').iterdir():
    if p.is_file():shutil.copyfile(p,dest/p.name)
index=dest/'index.html';s=index.read_text().replace('../ISCAS2025-FPGA-QUBO/static/','../static/').replace('../README.md','../docs/project.md');index.write_text(s)
docs=dest.parent/'docs';docs.mkdir(exist_ok=True)
for name in ['demo.md','sudoku.md','comparison_audit.md','benchmarks.md','spinnaker_comparison.md','iterations.md']:
    p=ROOT/'docs'/name
    if p.exists():shutil.copyfile(p,docs/name)
shutil.copyfile(ROOT/'README.md',docs/'project.md')
